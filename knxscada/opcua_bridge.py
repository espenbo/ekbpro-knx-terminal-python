"""Bridge between KNX and a PLC over OPC UA (e.g. CODESYS on a WAGO PFC).

The SCADA server is an OPC UA **client** of the PLC's OPC UA server. The PLC
program only needs a global variable list (generated by ``./scada plc-map``)
that is published in its Symbol Configuration – no OPC UA client licence and
no extra port on the PLC.

Data flow::

    KNX telegram ──ingest──▶ on_knx() ──▶ write PLC variable       (dir to_plc / both)
    PLC variable changes ──subscription──▶ _on_plc() ──▶ KNX write  (dir to_knx / both)

Rules that keep the bus safe:

* **No telegrams at start-up or reconnect.** The first value the
  subscription reports for a variable is only remembered; only *changes*
  after that are sent to KNX. Before subscribing, the PLC variables get the
  last known KNX values (writing to the PLC sends nothing to the bus).
* **No telegrams when the PLC restarts** (download, reset, online change
  with re-initialisation) while the connection stays up. Three guards:

  1. A report without a value or with a status other than Good (CODESYS
     sends these while it loads a new application) makes the variable
     unknown again: its next good value is only remembered, like the first.
  2. Changes towards KNX are held for ``settle_ms`` (500 ms). When more than
     ``burst_limit`` (8) variables change in that time, it is a restart,
     not the PLC program: nothing is sent.
  3. After a restart or a bad status, changes are only remembered for
     ``restart_quiet_s`` (15 s); then the PLC gets the KNX values again
     (as at start-up), so it shows what is really on the bus.
* **No echoes.** The last value exchanged per variable is remembered in both
  directions; a value equal to it is not sent back (REAL compared loosely).
* **Rate limit** per address towards KNX (``min_interval_ms``): if the PLC
  changes a value faster, the latest value is sent when the interval is over.

Writes to the PLC carry no timestamps – CODESYS rejects writes with a source
timestamp. Security: anonymous, user name/password and signed or encrypted
connections (``Basic256Sha256``, ``Aes128Sha256RsaOaep``, ``Aes256Sha256RsaPss``)
with a client certificate that is created automatically.
"""

