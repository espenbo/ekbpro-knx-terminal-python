log = logging.getLogger("knxscada.plc")

#: Application URI of our client certificate (must match the certificate).
APP_URI = "urn:ekbpro:knx-terminal-python:client"

#: IEC type → OPC UA variant type name.
VARIANT = {"BOOL": "Boolean", "REAL": "Float", "LREAL": "Double", "SINT": "SByte", "USINT": "Byte",
           "INT": "Int16", "UINT": "UInt16", "DINT": "Int32", "UDINT": "UInt32"}

#: security: "<policy>,<mode>" → asyncua policy class name.
POLICIES = {"basic256sha256": "SecurityPolicyBasic256Sha256",
            "aes128sha256rsaoaep": "SecurityPolicyAes128Sha256RsaOaep",
            "aes256sha256rsapss": "SecurityPolicyAes256Sha256RsaPss"}


def parse_security(text: str | None) -> tuple[str | None, str]:
    """``"Aes128Sha256RsaOaep,SignAndEncrypt"`` → ``("SecurityPolicyAes128Sha256RsaOaep", "SignAndEncrypt")``.

    ``None``/``"None"`` → ``(None, "None")``. Raises ValueError for unknown values.
    """
    if not text or str(text).strip().lower() == "none":
        return None, "None"
    parts = [p.strip() for p in str(text).split(",")]
    policy = POLICIES.get(parts[0].lower())
    mode = parts[1] if len(parts) > 1 else "SignAndEncrypt"
    if policy is None or mode not in ("Sign", "SignAndEncrypt"):
        raise ValueError(_("Invalid plc.security {value} – use None, or <policy>,Sign|SignAndEncrypt with policy "
                           "Basic256Sha256, Aes128Sha256RsaOaep or Aes256Sha256RsaPss").format(value=repr(text)))
    return policy, mode


async def make_client(cfg: Config):
    """An asyncua client configured from ``plc:`` (endpoint, user, security, certificate)."""
    from asyncua import Client, ua
    from asyncua.crypto import security_policies

    p = cfg.plc
    client = Client(url=str(p.get("endpoint") or "opc.tcp://127.0.0.1:4840"), timeout=float(p.get("timeout_s", 10)))
    client.application_uri = APP_URI
    client.name = "EKBPRO KNX Terminal Python"
    policy, mode = parse_security(p.get("security"))
    if p.get("username"):
        if policy is None:
            # Said before connecting: the password goes over the network in plain text.
            log.warning(_("PLC: the password is sent unencrypted (plc.security: None)"))
        client.set_user(str(p["username"]))
        client.set_password(str(p.get("password") or ""))
    if policy:
        cert = cfg.resolve(p.get("certificate", "var/opcua/client_cert.der"))
        key = cfg.resolve(p.get("private_key", "var/opcua/client_key.pem"))
        await ensure_certificate(cert, key)
        # Without server_certificate the PLC's certificate is taken from the (unauthenticated) endpoint
        # list; pinning it protects against a device on the network pretending to be the PLC.
        pinned = p.get("server_certificate")
        await client.set_security(getattr(security_policies, policy), str(cert), str(key),
                                  server_certificate=str(cfg.resolve(pinned)) if pinned else None,
                                  mode=getattr(ua.MessageSecurityMode, mode))
    return client


async def ensure_certificate(cert: Path, key: Path) -> None:
    """Create a self-signed client certificate (valid for years) if it does not exist yet."""
    if cert.exists() and key.exists():
        return
    from asyncua.crypto.cert_gen import setup_self_signed_certificate
    from cryptography.x509.oid import ExtendedKeyUsageOID

    cert.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    host = socket.gethostname()
    await setup_self_signed_certificate(
        key, cert, APP_URI, host, [ExtendedKeyUsageOID.CLIENT_AUTH],
        {"countryName": "NO", "organizationName": "EKBPRO", "commonName": f"EKBPRO KNX Terminal Python@{host}"},
    )
    key.chmod(0o600)  # the private key is for this program's account only
    log.info(_("Created the OPC UA client certificate %s – trust it in the PLC"), cert)


async def find_gvl(client, gvl: str, max_nodes: int = 5000) -> tuple[int, str] | None:
    """Find the GVL by browsing: returns ``(namespace index, node id prefix)`` or None.

    CODESYS publishes a GVL as ``ns=<n>;s=|var|<device>.Application.<GVL>``
    and its variables as ``…<GVL>.<variable>``.
    """
    from asyncua import ua

    queue = [(client.nodes.objects, 0)]
    visited = set()  # CODESYS reaches the same node through several paths
    while queue and len(visited) < max_nodes:
        node, depth = queue.pop(0)
        if node.nodeid in visited:
            continue
        visited.add(node.nodeid)
        ident = node.nodeid.Identifier
        if isinstance(ident, str) and (ident.endswith("." + gvl) or ident.endswith("|" + gvl)):
            return node.nodeid.NamespaceIndex, ident + "."
        if depth < 10:
            with contextlib.suppress(Exception):
                for child in await node.get_children(refs=ua.ObjectIds.HierarchicalReferences):
                    queue.append((child, depth + 1))
    return None


class _GvlChanged(Exception):
    """Variables that were missing now exist in the PLC (e.g. after an online change): reconnect."""


class _Handler:
    """asyncua subscription handler – forwards data changes to the bridge."""

    def __init__(self, bridge: PlcBridge) -> None:
        self.bridge = bridge

    def datachange_notification(self, node, val, data) -> None:
        status = getattr(getattr(getattr(data, "monitored_item", None), "Value", None), "StatusCode", None)
        good = status is None or status.is_good()
        self.bridge._on_plc(node.nodeid, val, good)

    def status_change_notification(self, status) -> None:  # connection problems
        self.bridge._lost.set()


class PlcBridge:
    """Keeps the PLC variables and the KNX group addresses in step (see module docstring)."""

    def __init__(self, server: ScadaServer, cfg: Config, pmap: PlcMap) -> None:
        self.server = server
        self.cfg = cfg
        self.p = cfg.plc
        self.entries = pmap.active()
        self.gvl = pmap.gvl
        self.by_ga: dict[str, list[PlcEntry]] = {}
        for e in self.entries:
            self.by_ga.setdefault(e.ga, []).append(e)
        self.connected = False
        self.client = None
        self.nodes: dict[str, Any] = {}        # var → asyncua Node
        self.by_nodeid: dict[Any, PlcEntry] = {}
        self.last: dict[str, Any] = {}         # var → last value exchanged (both directions)
        self.seen: set[str] = set()            # vars whose first subscription value has arrived
        self._to_plc: dict[str, Any] = {}      # var → value waiting to be written to the PLC
        self._writer: asyncio.Task | None = None
        self._last_sent: dict[str, float] = {}  # ga → time of the last KNX write from the PLC
        self._pending_knx: dict[str, asyncio.TimerHandle] = {}
        self._held: dict[str, tuple[PlcEntry, Any]] = {}   # var → change waiting for the settle time
        self._held_timer: asyncio.TimerHandle | None = None
        self._quiet_until = 0.0                # monotonic time until which PLC changes are only remembered
        self._resync: asyncio.TimerHandle | None = None
        self._lost = asyncio.Event()
        self._stop = False
        self._planned = False                  # a reconnect we asked for (no "disconnected" event)

    # -- life cycle ------------------------------------------------------------------------
    async def run(self) -> None:
        """Connect, synchronise and subscribe; reconnect with back-off when the connection is lost."""
        delay = 5
        while not self._stop:
            try:
                await self._session()
                delay = 5
            except asyncio.CancelledError:
                raise
            except _GvlChanged:
                delay = 1  # reconnect soon to pick up the new variables
            except Exception as exc:  # noqa: BLE001 - report every problem and retry
                if self.connected or delay == 5:
                    self.server.event("error", "plc", _("PLC (OPC UA): {error}. Retrying in {delay} s").format(
                        error=exc or type(exc).__name__, delay=delay))
            finally:
                await self._disconnect()
            if not self._stop:
                await asyncio.sleep(delay)
                delay = min(delay * 2, 60)

    async def stop(self) -> None:
        self._stop = True
        await self._disconnect()

    async def _session(self) -> None:
        from asyncua import ua

        self.client = await make_client(self.cfg)
        await self.client.connect()
        prefix, ns = self.p.get("node_prefix"), self.p.get("namespace")
        if not prefix:
            found = await find_gvl(self.client, self.gvl)
            if found is None:
                raise RuntimeError(_("GVL {gvl} not found on the PLC – is it in the Symbol Configuration?").format(gvl=self.gvl))
            ns, prefix = found
        self.nodes.clear()
        self.by_nodeid.clear()
        missing: list[tuple[PlcEntry, Any]] = []
        for e in self.entries:
            node = self.client.get_node(ua.NodeId(prefix + e.var, int(ns if ns is not None else 4)))
            try:
                await node.read_data_type()
            except Exception:  # noqa: BLE001 - variable not in the PLC
                missing.append((e, node))
                continue
            self.nodes[e.var] = node
            self.by_nodeid[node.nodeid] = e
        if missing:
            self.server.event("error", "plc", _("{n} variables are missing in the PLC (import the new GVL): {names}").format(
                n=len(missing), names=", ".join(e.var for e, _n in missing[:5]) + (" …" if len(missing) > 5 else "")))
        await self._sync_to_plc()
        self.seen.clear()
        self._lost.clear()
        handler = _Handler(self)
        sub = await self.client.create_subscription(int(self.p.get("publish_interval_ms", 200)), handler)
        watch = [self.nodes[e.var] for e in self.entries if e.dir in ("to_knx", "both") and e.var in self.nodes]
        if watch:
            await sub.subscribe_data_change(watch)
        self._set_connected(True)
        self.server.event("info", "plc", _("PLC (OPC UA) connected: {n} variables").format(n=len(self.nodes)))
        recheck = float(self.p.get("missing_recheck_s", 60))
        next_check = time.monotonic() + recheck
        while not self._stop and not self._lost.is_set():
            with contextlib.suppress(asyncio.TimeoutError):
                await asyncio.wait_for(self._lost.wait(), 5)
            await self.client.check_connection()  # raises when the PLC is gone
            if missing and time.monotonic() >= next_check:
                # After an online change the new GVL variables appear: reconnect to use them
                # (the same start-up rules apply – nothing is sent to KNX).
                next_check = time.monotonic() + recheck
                if await self._any_exists(missing):
                    self.server.event("info", "plc", _("New variables in the PLC – reconnecting"))
                    self._planned = True
                    raise _GvlChanged()
        if self._lost.is_set() and not self._stop:
            raise ConnectionError(_("connection lost"))

    @staticmethod
    async def _any_exists(missing: list) -> bool:
        """True if at least one of the missing variables exists now (checks the first few)."""
        for _e, node in missing[:3]:
            try:
                await node.read_data_type()
                return True
            except Exception:  # noqa: BLE001 - still missing
                continue
        return False

    async def _disconnect(self) -> None:
        was = self.connected and not self._planned
        self._planned = False
        self._set_connected(False)
        for h in self._pending_knx.values():
            h.cancel()
        self._pending_knx.clear()
        self._drop_held()
        if self._resync is not None:
            self._resync.cancel()
            self._resync = None
        if self.client is not None:
            with contextlib.suppress(Exception):
                await asyncio.wait_for(self.client.disconnect(), 3)
            self.client = None
        if was:
            self.server.event("error", "plc", _("PLC (OPC UA) disconnected"))

    def _set_connected(self, connected: bool) -> None:
        if connected != self.connected or self.server.status.get("plc") is None:
            self.connected = connected
            self.server.status["plc"] = "connected" if connected else "disconnected"
            self.server._broadcast({"type": "status", "status": self.server.status})

    # -- KNX → PLC -------------------------------------------------------------------------
    async def _sync_to_plc(self) -> None:
        """Give the PLC the last known KNX values (no bus traffic) before subscribing."""
        for e in self.entries:
            if e.dir in ("to_plc", "both") and e.var in self.nodes:
                st = self.server.state.get(e.ga)
                if st and st.get("value") is not None:
                    await self._write_plc(e, st["value"])

    def on_knx(self, ga: str, value: Any) -> None:
        """Called by the server for every write/response telegram (also our own)."""
        if not self.connected:
            return
        for e in self.by_ga.get(ga, ()):
            if e.dir in ("to_plc", "both") and e.var in self.nodes:
                v = to_plc_value(e, value)
                if v is not None and not same_value(v, self.last.get(e.var)):
                    self._to_plc[e.var] = (e, value)
        if self._to_plc and (self._writer is None or self._writer.done()):
            self._writer = asyncio.create_task(self._drain_to_plc())

    async def _drain_to_plc(self) -> None:
        """Write queued values (only the latest per variable) to the PLC."""
        while self._to_plc and self.connected:
            var, (e, value) = next(iter(self._to_plc.items()))
            del self._to_plc[var]
            try:
                await self._write_plc(e, value)
            except Exception as exc:  # noqa: BLE001
                log.warning("PLC write %s failed: %s", var, exc)

    async def _write_plc(self, e: PlcEntry, knx_value: Any) -> None:
        from asyncua import ua

        v = to_plc_value(e, knx_value)
        if v is None:
            return
        vt = getattr(ua.VariantType, "String" if e.type.startswith("STRING") else VARIANT[e.type])
        self.last[e.var] = v  # before the write: the subscription echo must be recognised
        # A DataValue without timestamps: CODESYS rejects writes that carry a source timestamp.
        await self.nodes[e.var].write_value(ua.DataValue(ua.Variant(v, vt)))

    # -- PLC → KNX -------------------------------------------------------------------------
    def _on_plc(self, nodeid, value: Any, good: bool = True) -> None:
        e = self.by_nodeid.get(nodeid)
        if e is None or e.dir not in ("to_knx", "both"):
            return
        if not good or value is None:
            # The PLC is loading or resetting: the variable is unknown until it reports a good value again.
            self.seen.discard(e.var)
            self._held.pop(e.var, None)
            self._enter_quiet(_("the PLC reported variables without a value (download or reset?)"))
            return
        if e.var not in self.seen or time.monotonic() < self._quiet_until:
            # First report after (re)connecting or after a PLC restart = the current PLC value,
            # not a change made by the PLC program: remembered, never sent to KNX.
            self.seen.add(e.var)
            self.last[e.var] = value
            return
        if same_value(value, self.last.get(e.var)):
            return  # our own write coming back, or no real change
        self.last[e.var] = value
        self._held[e.var] = (e, value)
        if self._held_timer is None:
            settle = float(self.p.get("settle_ms", 500)) / 1000
            self._held_timer = asyncio.get_running_loop().call_later(settle, self._release_held)

    def _release_held(self) -> None:
        """End of the settle time: send the changes – unless so many came at once that the PLC restarted."""
        self._held_timer = None
        held, self._held = self._held, {}
        limit = int(self.p.get("burst_limit", 8))
        if limit and len(held) > limit:
            self._enter_quiet(_("{n} PLC variables changed at once (download or reset?)").format(n=len(held)))
            return
        for e, value in held.values():
            self._schedule_knx(e, value)

    def _drop_held(self) -> None:
        if self._held_timer is not None:
            self._held_timer.cancel()
            self._held_timer = None
        self._held.clear()

    def _enter_quiet(self, reason: str) -> None:
        """Treat it as a PLC restart: send nothing, remember values for a while, then re-sync the PLC."""
        self._drop_held()
        for h in self._pending_knx.values():
            h.cancel()
        self._pending_knx.clear()
        quiet = float(self.p.get("restart_quiet_s", 15))
        first = time.monotonic() >= self._quiet_until
        self._quiet_until = time.monotonic() + quiet
        if self._resync is not None:
            self._resync.cancel()
        loop = asyncio.get_running_loop()
        self._resync = loop.call_later(quiet, lambda: loop.create_task(self._resync_plc()))
        if first:
            self.server.event("error", "plc", _("PLC restart detected – nothing sent to KNX: {reason}").format(
                reason=reason))

    async def _resync_plc(self) -> None:
        """After a PLC restart: give the PLC the KNX values again (no bus traffic)."""
        self._resync = None
        if not self.connected:
            return
        try:
            await self._sync_to_plc()
        except Exception as exc:  # noqa: BLE001 - the PLC may still be starting; the next reconnect syncs too
            log.warning("PLC re-sync failed: %s", exc)
            return
        self.server.event("info", "plc", _("PLC re-synchronised with the KNX values"))

    def _schedule_knx(self, e: PlcEntry, value: Any) -> None:
        """Send now, or – within the rate limit – once the interval is over (latest value wins)."""
        loop = asyncio.get_running_loop()
        gap = float(self.p.get("min_interval_ms", 200)) / 1000
        wait = self._last_sent.get(e.ga, 0) + gap - time.monotonic()
        old = self._pending_knx.pop(e.ga, None)
        if old:
            old.cancel()
        if wait <= 0:
            loop.create_task(self._send_knx(e, value))
        else:
            self._pending_knx[e.ga] = loop.call_later(wait, lambda: loop.create_task(self._send_knx(e, value)))

    async def _send_knx(self, e: PlcEntry, value: Any) -> None:
        self._pending_knx.pop(e.ga, None)
        self._last_sent[e.ga] = time.monotonic()
        try:
            knx_value = to_knx_value(e, value)
            payload = dptlib.encode(e.dpt, knx_value)
            await self.server._send(e.ga, "write", payload)
        except Exception as exc:  # noqa: BLE001 - e.g. KNX not connected, value out of range
            self.server.event("error", "plc", _("PLC → KNX {address} failed: {error}").format(address=e.ga, error=exc))
            return
        shown = dptlib.fmt(e.dpt, dptlib.decode(e.dpt, payload))
        self.server.event("info", "operation", f"{e.ga} {e.name} ← {shown}", "plc")


async def browse(cfg: Config, text_filter: str = "", limit: int = 400) -> list[tuple[str, str]]:
    """List variables on the PLC (``./scada plc-browse``): ``[(node id, data type)]``."""
    from asyncua import ua

    client = await make_client(cfg)
    out: list[tuple[str, str]] = []
    async with client:
        queue = [(client.nodes.objects, 0)]
        visited = set()  # CODESYS reaches the same variable through several paths: list it once
        while queue and len(visited) < 20000 and len(out) < limit:
            node, depth = queue.pop(0)
            if node.nodeid in visited:
                continue
            visited.add(node.nodeid)
            try:
                cls = await node.read_node_class()
            except Exception:  # noqa: BLE001
                continue
            ident = str(node.nodeid.to_string())
            if cls == ua.NodeClass.Variable and (not text_filter or text_filter.lower() in ident.lower()):
                with contextlib.suppress(Exception):
                    dt = await node.read_data_type_as_variant_type()
                    out.append((ident, dt.name))
                continue
            if depth < 10:
                with contextlib.suppress(Exception):
                    for child in await node.get_children(refs=ua.ObjectIds.HierarchicalReferences):
                        queue.append((child, depth + 1))
    return out


async def endpoints(cfg: Config) -> list[str]:
    """What the PLC offers, without logging in (``./scada plc-browse --endpoints``): security and login types."""
    from asyncua import Client

    client = Client(url=str(cfg.plc.get("endpoint") or "opc.tcp://127.0.0.1:4840"), timeout=float(cfg.plc.get("timeout_s", 10)))
    out = []
    for e in await client.connect_and_get_server_endpoints():
        tokens = ", ".join(t.TokenType.name for t in e.UserIdentityTokens)
        out.append(f"{e.SecurityMode.name.rstrip('_'):<15} {e.SecurityPolicyUri.split('#')[-1]:<22} {tokens}")
    return out

